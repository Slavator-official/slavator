#!/usr/bin/env python3
"""Проверка платформенных частей: звук и синтез ввода.

Записать здесь нечего: на сборочной машине нет ни звуковых устройств, ни
рабочего стола. Проверяется то, что поддаётся проверке без них, — и это
всё равно ловит самые дорогие ошибки:

* модули вообще загружаются;
* размер структуры для SendInput совпадает с тем, что ждёт Windows —
  при несовпадении система молча ничего не печатает, и найти причину
  почти невозможно;
* перечисление звуковых устройств не роняет процесс;
* склейка устоявшейся части расшифровки считается верно — на маке
  ошибка ровно здесь заставляла диктовку замолкать навсегда.

Отдельным файлом, а не строкой внутри сборки: многострочный текст внутри
YAML требует отступов, которых PowerShell не допускает, и сборка ломалась
на разборе файла. Заодно это можно запустить руками.
"""
from __future__ import annotations

import ctypes
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))


def main() -> int:
    import dictation
    import live_capture

    if live_capture.RATE != 16000:
        print(f"ОШИБКА: частота записи {live_capture.RATE}, а ядро ждёт 16000")
        return 1

    # Структура INPUT: 28 байт на 32-битном питоне, 40 на 64-битном.
    size = ctypes.sizeof(dictation._Input)
    if size not in (28, 40):
        print(f"ОШИБКА: размер INPUT {size} — SendInput такое не примет")
        return 1
    print(f"размер структуры ввода: {size} байт — верно")

    stable = dictation.Dictation._stable("Давайте за", "Давайте зафиксируем")
    if stable != "Давайте ":
        print(f"ОШИБКА: склейка вернула {stable!r}, ожидалось 'Давайте '")
        return 1
    print("склейка устоявшейся части: верно")

    # Устройств на сборочной машине нет, и это нормально. Важно, что вызов
    # не роняет процесс и внятно объясняет, чего не хватает.
    info = live_capture.devices()
    if info.get("ok"):
        print(f"звуковые устройства: динамиков {len(info['speakers'])}, "
              f"микрофонов {len(info['microphones'])}, "
              f"петель {len(info['loopback'])}")
    else:
        print(f"звуковых устройств нет: {info.get('error', '')} — "
              "на сборочной машине это ожидаемо")

    print("платформенные части в порядке")
    return 0


if __name__ == "__main__":
    sys.exit(main())
